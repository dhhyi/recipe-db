"""Validate GraphQL operations and emit independent Zig query constants."""

import argparse
from pathlib import Path
import subprocess
import sys

from graphql import GraphQLError, Source, build_schema, parse, print_ast, validate
from graphql.language import OperationDefinitionNode
from graphql.utilities import separate_operations


ROOT = Path(__file__).resolve().parent


def generate(schema_source, operations_source):
    schema = build_schema(schema_source)
    document = parse(operations_source)
    errors = validate(schema, document)
    if errors:
        raise ValueError("\n\n".join(str(error) for error in errors))
    operations = [
        node for node in document.definitions if isinstance(node, OperationDefinitionNode)
    ]
    if not operations or any(node.name is None for node in operations):
        raise ValueError("All operations must be named; at least one is required.")
    lines = ["// Generated by generate_operations.py. Do not edit.", ""]
    for name, operation in separate_operations(document).items():
        lines.append(f'pub const @"{name}" =')
        lines.extend("    \\\\" + line for line in print_ast(operation).splitlines())
        lines.extend([";", ""])
    return subprocess.run(
        ["zig", "fmt", "--stdin"],
        input="\n".join(lines),
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=ROOT / "recipe-db.graphqls")
    parser.add_argument("--operations", type=Path, default=ROOT / "src/operations.graphql")
    parser.add_argument("--output", type=Path, default=ROOT / "src/operations.zig")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = generate(
            Source(args.schema.read_text(encoding="utf-8"), str(args.schema)),
            Source(args.operations.read_text(encoding="utf-8"), str(args.operations)),
        )
        if args.check:
            if args.output.read_text(encoding="utf-8") != generated:
                raise ValueError(
                    f"{args.output} is stale; run python3 generate_operations.py."
                )
        else:
            args.output.write_text(generated, encoding="utf-8")
    except subprocess.CalledProcessError as error:
        print(error.stderr, file=sys.stderr)
        return 1
    except (OSError, GraphQLError, ValueError, TypeError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
