#!/bin/sh
set -eu

if [ "$#" -ne 0 ]; then
  echo "usage: generate-docker-compose.sh" >&2
  exit 2
fi

project_root=$(cd "$(dirname "$0")/.." && pwd)
. "$project_root/.scripts/lib/project-metadata.sh"
output_compose="$project_root/docker-compose.yml"
output_oauth="$project_root/oauth2-proxy-alpha.yml"
generated_directory="$project_root/.generated"

yq() {
  mise exec -- yq "$@"
}

jq() {
  mise exec -- jq "$@"
}

sh "$project_root/.scripts/refresh-render-inputs.sh"
work_directory="$generated_directory/compose-render.$$"
mkdir "$work_directory"
trap 'rm -rf "$work_directory"' EXIT HUP INT TERM

data_values="$work_directory/data-values.yml"
fragments="$work_directory/project-fragments.jsonl"
jq -n \
  --slurpfile inputs "$generated_directory/compose-inputs.json" \
  '{registryCacheSuffix:$inputs[0].registryCacheSuffix,
    googleOAuthClientId:$inputs[0].googleOAuthClientId,
    developmentUser:$inputs[0].developmentUser,
    projects:[]}' > "$data_values"
project_metadata_to_jsonl "$project_root" "$fragments"
jq --slurpfile projects "$fragments" \
  '.projects = $projects' "$data_values" > "$work_directory/next.yml"
mv "$work_directory/next.yml" "$data_values"

render() {
  render_template=$1
  render_output=$2
  echo "Rendering $render_output..."
  printf '%s\n' '# This file is generated by ytt. Use mise run generate-docker-compose to regenerate it.' > "$render_output"
  mise exec -- ytt \
    -f "$project_root/.scripts/templates/$render_template-template.yml" \
    -f "$project_root/.scripts/templates/browse-maintenance-template.lib.yml" \
    -f "$project_root/.scripts/templates/service-template.lib.yml" \
    -f "$project_root/.scripts/templates/fixtures-service-template.lib.yml" \
    -f "$project_root/.scripts/templates/traefik-service-template.lib.yml" \
    -f "$project_root/.scripts/templates/nats-service-template.lib.yml" \
    --data-values-file "$data_values" >> "$render_output"
}

render docker-compose "$work_directory/docker-compose.yml"
render oauth2-proxy-alpha "$work_directory/oauth2-proxy-alpha.yml"

for output in "$output_compose" "$output_oauth"; do
  rendered="$work_directory/${output##*/}"
  if [ ! -f "$output" ] || ! cmp -s "$rendered" "$output"; then
    mv -f "$rendered" "$output"
  fi
done
