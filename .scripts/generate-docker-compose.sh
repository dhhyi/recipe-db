#!/bin/sh
#USAGE arg "[modes]" var=#true help="Combine production/prod, backend (no frontends), and prepare (keep existing configuration)" {
#USAGE   choices "prod" "production" "backend" "prepare"
#USAGE }
set -eu

project_root=$(cd "$(dirname "$0")/.." && pwd)
. "$project_root/.scripts/lib/project-metadata.sh"
output_compose="$project_root/docker-compose.yml"
output_traefik="$project_root/traefik.yml"
production=false
backend_only=false
prepare=false

yq() {
  mise exec -- yq "$@"
}

jq() {
  mise exec -- jq "$@"
}

for argument in "$@"; do
  case "$argument" in
    prod | production) production=true ;;
    backend) backend_only=true ;;
    prepare) prepare=true ;;
    *)
      echo "unknown argument: $argument" >&2
      exit 1
      ;;
  esac
done

if [ "$prepare" = true ] && [ -f "$output_compose" ]; then
  echo "docker-compose.yml already exists, skipping generation"
  exit 0
fi

if [ "$production" = true ]; then
  echo "Setting up for production..."
else
  echo "Setting up for development..."
fi

temporary_directory=$(mktemp -d)
trap 'rm -rf "$temporary_directory"' EXIT

data_values="$temporary_directory/data-values.yml"
fragments="$temporary_directory/project-fragments.jsonl"
ci=false
if [ -n "${CI:-}" ]; then
  ci=true
fi
jq -n \
  --argjson production "$production" \
  --argjson backendOnly "$backend_only" \
  --argjson ci "$ci" \
  --arg registryCacheSuffix "${REGISTRY_CACHE_SUFFIX:-}" \
  --arg googleOAuthClientId "${GOOGLE_OAUTH_CLIENT_ID:-replace-with-google-oauth-client-id}" \
  --arg developmentUser "$(id -u):$(id -g)" \
  '{production: $production, backendOnly: $backendOnly, ci: $ci, registryCacheSuffix: $registryCacheSuffix, googleOAuthClientId: $googleOAuthClientId, developmentUser: $developmentUser, projects: []}' \
  > "$data_values"
project_metadata_to_jsonl "$project_root" "$fragments"

jq --slurpfile projects "$fragments" \
  '.projects = $projects' "$data_values" > "$temporary_directory/next.yml"
mv "$temporary_directory/next.yml" "$data_values"

render() {
  render_template=$1
  render_output=$2
  echo "Rendering $render_output..."
  set -- \
    -f "$project_root/.scripts/templates/$render_template-template.yml" \
    -f "$project_root/.scripts/templates/browse-maintenance-template.lib.yml" \
    -f "$project_root/.scripts/templates/service-template.lib.yml" \
    --data-values-file "$data_values"
  if [ "$render_template" = docker-compose ]; then
    set -- "$@" \
      -f "$project_root/.scripts/templates/fixtures-service-template.lib.yml" \
      -f "$project_root/.scripts/templates/traefik-service-template.lib.yml" \
      -f "$project_root/.scripts/templates/nats-service-template.lib.yml"
  fi
  printf '%s\n' '# This file is generated by ytt. Use mise run generate-docker-compose to regenerate it.' > "$render_output"
  mise exec -- ytt "$@" >> "$render_output"
}

render docker-compose "$output_compose"
if jq -e '.projects | any(.name == "graphql")' "$data_values" > /dev/null; then
  render oauth2-proxy-alpha "$project_root/oauth2-proxy-alpha.yml"
else
  rm -f "$project_root/oauth2-proxy-alpha.yml"
fi
if [ "$production" = true ]; then
  render traefik "$output_traefik"
else
  rm -f "$output_traefik"
fi
