#!/usr/bin/env bash
set -euo pipefail

workspace_root=$(cd -- "$(dirname -- "$0")/.." && pwd -P)
cd "$workspace_root"

output=$(mktemp .BUILD.bazel.XXXXXX)
integration_metadata=$(mktemp)
integration_graph=$(mktemp)
trap 'rm -f "$output" "$integration_metadata" "$integration_graph"' EXIT

printf '%s\n' '# Generated by generate-bazel-build.sh. Do not edit it manually.' > "$output"

quote() {
  jq -Rn --arg value "$1" '$value'
}

for project_file in */.project.yaml; do
  project=${project_file%/.project.yaml}
  yq eval-all -o=json 'select(documentIndex == 1)' "$project_file" \
    | jq -c --arg name "$project" '. + {name:$name}' >> "$integration_metadata"
done
python3 .scripts/integration-dependencies.py \
  --metadata "$integration_metadata" --schema .scripts/project-schema.json > "$integration_graph"

emit_rule() {
  local name=$1 archive=$2 script=$3 dependency=$4 action=$5
  shift 5
  {
    printf '\ngenrule(\n'
    printf '    name = "%s",\n' "$name"
    printf '    srcs = [\n'
    for file in "$@"; do
      printf '        %s,\n' "$(quote "$file")"
    done
    if [[ -n "$dependency" ]]; then
      printf '        %s,\n' "$(quote ":$dependency")"
    fi
    printf '        %s,\n' "$(quote "$script")"
    if [[ "$archive" == *.tar ]]; then
      printf '        %s,\n' "$(quote .scripts/bazel-artifacts.sh)"
    fi
    printf '        %s,\n' "$(quote .scripts/run-in-devcontainer.sh)"
    if [[ "$script" == .scripts/format-bazel.sh ]]; then
      printf '        %s,\n' "$(quote .scripts/format-files.sh)"
      printf '        %s,\n' "$(quote .scripts/format-check.sh)"
    fi
    printf '        %s,\n' "$(quote mise.toml)"
    printf '        %s,\n' "$(quote .mise/config.toml)"
    printf '        %s,\n' "$(quote .mise/tasks/project-actions.toml)"
    printf '    ],\n'
    printf '    outs = ["%s"],\n' "$archive"
    if [[ "$script" == .scripts/bazel-project-action.sh ]]; then
      printf '    cmd = "sh %s %s %s %s' "\$(location $script)" "$project" "$action" "\$@"
      if [[ -n "$dependency" ]]; then
        printf ' %s' "\$(location :$dependency)"
      fi
    else
      printf '    cmd = "sh %s %s %s' "\$(location $script)" "$project" "\$@"
      if [[ -n "$dependency" ]]; then
        printf ' %s' "\$(location :$dependency)"
      fi
    fi
    # Bazel replays streams separately; keep group markers with command output.
    printf ' 2>&1",\n'
    printf '    tags = ["no-sandbox", "no-remote"],\n'
    printf ')\n'
  } >> "$output"
}

for project_file in */.project.yaml; do
  project=${project_file%/.project.yaml}
  check=$(yq eval-all -r 'select(documentIndex == 1) | .check // ""' "$project_file")
  test=$(yq eval-all -r 'select(documentIndex == 1) | .test // ""' "$project_file")
  format_count=$(yq eval-all -r 'select(documentIndex == 1) | .format // [] | length' "$project_file")
  generators=$(yq eval-all -r 'select(documentIndex == 1) | .generate // [] | length' "$project_file")
  [[ -n "$check" || -n "$test" || "$format_count" -gt 0 || "$generators" -gt 0 ]] || continue

  files=()
  format_files=()
  declare -A included_files=()
  while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    format_files+=("$file")
    case "${file##*/}" in
      README.md | Dockerfile | .dockerignore) continue ;;
    esac
    files+=("$file")
    included_files["$file"]=1
  done < <(git ls-files --cached --others --exclude-standard -z -- "$project/" | sort -z)

  for file in "$project/.devcontainer/devcontainer.json" "$project/.devcontainer/Dockerfile"; do
    if [[ -f "$file" && -z ${included_files["$file"]+x} ]]; then
      files+=("$file")
      included_files["$file"]=1
    fi
  done

  graphql_schema=$(yq eval-all -r 'select(documentIndex == 1) | .graphqlSchema // ""' "$project_file")
  if [[ -n "$graphql_schema" ]]; then
    schema_file="$project/$graphql_schema/recipe-db.graphqls"
    if [[ ! -f "$schema_file" ]]; then
      printf 'Missing generated GraphQL schema: %s (run mise run sync)\n' "$schema_file" >&2
      exit 1
    fi
    schema_file=$(realpath --relative-to="$workspace_root" "$schema_file")
    if [[ -z ${included_files["$schema_file"]+x} ]]; then
      files+=("$schema_file")
      format_files+=("$schema_file")
    fi
  fi

  if [[ "$project" == design ]]; then
    for source_project_file in */.project.yaml; do
      source_project=${source_project_file%/.project.yaml}
      while IFS= read -r source; do
        [[ -n "$source" ]] || continue
        source_path="$source_project/$source"
        if [[ ! -e "$source_path" ]]; then
          printf 'Missing Tailwind source: %s (run mise run sync)\n' "$source_path" >&2
          exit 1
        fi
        if [[ -z ${included_files["$source_project_file"]+x} ]]; then
          files+=("$source_project_file")
          included_files["$source_project_file"]=1
        fi
        while IFS= read -r -d '' file; do
          [[ -f "$file" && -z ${included_files["$file"]+x} ]] || continue
          files+=("$file")
          included_files["$file"]=1
        done < <(git ls-files --cached --others --exclude-standard -z -- "$source_path" | sort -z)
      done < <(yq eval-all -r 'select(documentIndex == 1) | .tailwind.sources // [] | .[]' "$source_project_file")
    done
  fi

  generation_dependency=
  if [[ "$generators" -gt 0 ]]; then
    generation_dependency="${project}_generate"
    emit_rule "$generation_dependency" "$project-generate.tar" .scripts/generate-bazel.sh "" "" "${format_files[@]}"
  fi

  if [[ "$format_count" -gt 0 ]]; then
    formatting_inputs=()
    declare -A formatting_included=()
    for file in "${format_files[@]}"; do
      case "$file" in
        *.md) continue ;;
      esac
      formatting_inputs+=("$file")
      formatting_included["$file"]=1
    done
    for file in "$project/.devcontainer/devcontainer.json" "$project/.devcontainer/Dockerfile"; do
      if [[ -f "$file" && -z ${formatting_included["$file"]+x} ]]; then
        formatting_inputs+=("$file")
        formatting_included["$file"]=1
      fi
    done
    resolved=$(mktemp)
    if ! bash .scripts/format-files.sh "$project" > "$resolved"; then
      rm -f "$resolved"
      exit 1
    fi
    while IFS= read -r -d '' file; do
      file="$project/$file"
      if [[ -z ${formatting_included["$file"]+x} ]]; then
        formatting_inputs+=("$file")
      fi
    done < "$resolved"
    rm -f "$resolved"
    emit_rule "${project}_format_check" "$project-format-check.ok" .scripts/format-bazel.sh "" "" "${formatting_inputs[@]}"
  fi

  if [[ -n "$check" ]]; then
    emit_rule "${project}_check" "$project-check.ok" .scripts/bazel-project-action.sh "$generation_dependency" check "${files[@]}"
    precommit_files=("${files[@]}")
    if [[ "$format_count" -gt 0 ]]; then
      precommit_files+=(":${project}_format_check")
    fi
    emit_rule "${project}_precommit" "$project-precommit.ok" .scripts/bazel-project-action.sh "$generation_dependency" check "${precommit_files[@]}"
  fi

  if [[ -n "$test" ]]; then
    emit_rule "${project}_test" "$project-test.ok" .scripts/bazel-project-action.sh "$generation_dependency" test "${files[@]}"
  fi
done

{
  printf '\ngenrule(\n'
  printf '    name = "shellcheck",\n'
  printf '    srcs = [\n'
  while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    printf '        %s,\n' "$(quote "$file")"
  done < <(git ls-files --cached --others --exclude-standard -z -- '*.sh' '*.bash' '*.bats' | sort -zu)
  printf '    ],\n'
  printf '    tools = ["mise.toml", ".mise/config.toml"],\n'
  printf '    outs = ["shellcheck.ok"],\n'
  printf '    cmd = "mise exec -- shellcheck %s && touch %s",\n' "\$(SRCS)" "\$@"
  printf '    tags = ["no-sandbox", "no-remote"],\n'
  printf ')\n'
} >> "$output"

manifest=.scripts/tests/groups.yaml
group_specs=$(yq -o=json '.' "$manifest")
if ! jq -e '
  type == "object" and length > 0 and all(to_entries[];
    (.key | test("^[a-z][a-z0-9_]*$")) and
    (.value.tests | type == "array" and length > 0 and all(.[]; type == "string")) and
    (.value.suite_inputs | type == "object") and
    ((.value.tests | sort) == (.value.suite_inputs | keys | sort)) and
    (.value.suite_inputs | all(.[]; type == "array" and all(.[]; type == "string" and length > 0))) and
    ((.value.exclusive_tests // []) | type == "array" and all(.[]; type == "string")))
' <<< "$group_specs" > /dev/null; then
  printf 'Invalid script test group manifest: %s\n' "$manifest" >&2
  exit 1
fi

declare -A test_groups=()
for group in $(jq -r 'keys[]' <<< "$group_specs"); do
  while IFS= read -r test_file; do
    if [[ "$test_file" != .scripts/tests/*.bats || ! -f "$test_file" ]]; then
      printf 'Missing or invalid script test: %s\n' "$test_file" >&2
      exit 1
    fi
    if [[ -n ${test_groups["$test_file"]+x} ]]; then
      printf 'Script test assigned more than once: %s\n' "$test_file" >&2
      exit 1
    fi
    test_groups["$test_file"]=$group
  done < <(jq -r --arg group "$group" '.[$group].tests[]' <<< "$group_specs")
done

while IFS= read -r -d '' test_file; do
  [[ -f "$test_file" ]] || continue
  if [[ -z ${test_groups["$test_file"]+x} ]]; then
    printf 'Script test is not assigned to a group: %s\n' "$test_file" >&2
    exit 1
  fi
done < <(git ls-files --cached --others --exclude-standard -z -- '.scripts/tests/*.bats' | sort -zu)

for group in $(jq -r 'keys[]' <<< "$group_specs"); do
  suite_targets=()
  while IFS= read -r test_file; do
    suite_id=${test_file#".scripts/tests/"}
    suite_id=${suite_id%.bats}
    suite_id=${suite_id//[^a-zA-Z0-9_-]/_}
    suite_target="test_scripts_suite_$suite_id"
    exclusive=false
    if jq -e --arg group "$group" --arg test "$test_file" '.[$group].exclusive_tests // [] | index($test) != null' <<< "$group_specs" > /dev/null; then
      exclusive=true
    fi
    declare -A suite_files=()
    suite_files["$manifest"]=1
    suite_files[".scripts/tests/test_helper.bash"]=1
    suite_files[".scripts/test-scripts.sh"]=1
    suite_files[".scripts/run-script-test.sh"]=1
    suite_files["mise.toml"]=1
    suite_files[".mise/config.toml"]=1
    suite_files[".mise/tasks/script-tests.toml"]=1
    suite_files[".bazelversion"]=1
    suite_files["$test_file"]=1
    while IFS= read -r pattern; do
      matched=false
      while IFS= read -r -d '' file; do
        [[ -f "$file" ]] || continue
        suite_files["$file"]=1
        matched=true
      done < <(git ls-files --cached --others --exclude-standard -z -- "$pattern" | sort -zu)
      if [[ "$matched" == false ]]; then
        printf 'Script test suite %s input pattern matches no files: %s\n' "$test_file" "$pattern" >&2
        exit 1
      fi
    done < <(jq -r --arg group "$group" --arg test "$test_file" \
      '.[$group].suite_inputs[$test][]' <<< "$group_specs")

    {
      printf '\nsh_test(\n'
      printf '    name = "%s",\n' "$suite_target"
      printf '    srcs = [\n'
      printf '        ".scripts/run-script-test.sh",\n'
      printf '    ],\n'
      printf '    args = [%s],\n' "$(quote "$test_file")"
      printf '    data = [\n'
      while IFS= read -r file; do
        if [[ "$file" != ".scripts/run-script-test.sh" ]]; then
          printf '        %s,\n' "$(quote "$file")"
        fi
      done < <(printf '%s\n' "${!suite_files[@]}" | sort)
      printf '    ],\n'
      printf '    timeout = "moderate",\n'
      if [[ "$exclusive" == true ]]; then
        printf '    tags = ["exclusive", "no-sandbox", "no-remote"],\n'
      else
        printf '    tags = ["no-sandbox", "no-remote"],\n'
      fi
      printf ')\n'
    } >> "$output"
    suite_targets+=("$suite_target")
  done < <(jq -r --arg group "$group" '.[$group].tests[]' <<< "$group_specs")
  {
    printf '\ntest_suite(\n'
    printf '    name = "test_scripts_%s",\n' "$group"
    printf '    tests = [\n'
    for suite_target in "${suite_targets[@]}"; do
      printf '        %s,\n' "$(quote ":$suite_target")"
    done
    printf '    ],\n'
    printf ')\n'
  } >> "$output"
done

{
  printf '\ntest_suite(\n'
  printf '    name = "test_scripts",\n'
  printf '    tests = [\n'
  while IFS= read -r group; do
    printf '        ":test_scripts_%s",\n' "$group"
  done < <(jq -r 'keys[]' <<< "$group_specs")
  printf '    ],\n'
  printf ')\n'
} >> "$output"

