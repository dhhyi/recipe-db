#!/usr/bin/env bash
set -euo pipefail

workspace_root=$(cd -- "$(dirname -- "$0")/.." && pwd -P)
cd "$workspace_root"

output=$(mktemp .BUILD.bazel.XXXXXX)
trap 'rm -f "$output"' EXIT

printf '%s\n' '# Generated by generate-bazel-build.sh. Do not edit it manually.' > "$output"

quote() {
  jq -Rn --arg value "$1" '$value'
}

emit_check_rule() {
  local project=$1 identity=$2
  shift 2
  {
    printf '\ngenrule(\n'
    printf '    name = "%s_check",\n' "$project"
    printf '    srcs = [\n'
    for file in "$@"; do
      printf '        %s,\n' "$(quote "$file")"
    done
    printf '        %s,\n' "$(quote "$identity")"
    printf '        %s,\n' "$(quote .scripts/bazel-check.sh)"
    printf '        %s,\n' "$(quote .scripts/run-in-devcontainer.sh)"
    printf '        %s,\n' "$(quote mise.toml)"
    printf '        %s,\n' "$(quote .bazelversion)"
    printf '    ],\n'
    printf '    outs = ["%s-check.ok"],\n' "$project"
    printf "    cmd = \"sh \$(location .scripts/bazel-check.sh) %s \$@\",\n" "$project"
    printf '    tags = ["no-sandbox", "no-remote"],\n'
    printf ')\n'
    printf '\nalias(\n'
    printf '    name = "%s_precommit",\n' "$project"
    printf '    actual = ":%s_check",\n' "$project"
    printf ')\n'
  } >> "$output"
}

quality_targets=()
for project_file in */.project.yaml; do
  project=${project_file%/.project.yaml}
  check=$(yq eval-all -r 'select(documentIndex == 1) | .check // ""' "$project_file")
  format=$(yq eval-all -r 'select(documentIndex == 1) | .format // ""' "$project_file")
  generators=$(yq eval-all -r 'select(documentIndex == 1) | .generate // [] | length' "$project_file")
  [[ -n "$check" || -n "$format" || "$generators" -gt 0 ]] || continue

  files=()
  declare -A included_files=()
  while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    case "${file##*/}" in
      README.md | Dockerfile | .dockerignore) continue ;;
    esac
    files+=("$file")
    included_files["$file"]=1
  done < <(git ls-files --cached --others --exclude-standard -z -- "$project/" | sort -z)

  graphql_schema=$(yq eval-all -r 'select(documentIndex == 1) | .graphqlSchema // ""' "$project_file")
  if [[ -n "$graphql_schema" ]]; then
    schema_file="$project/$graphql_schema/recipe-db.graphqls"
    if [[ ! -f "$schema_file" ]]; then
      printf 'Missing generated GraphQL schema: %s (run mise run sync)\n' "$schema_file" >&2
      exit 1
    fi
    schema_file=$(realpath --relative-to="$workspace_root" "$schema_file")
    if [[ -z ${included_files["$schema_file"]+x} ]]; then
      files+=("$schema_file")
    fi
  fi

  if [[ "$project" == design ]]; then
    for source_project_file in */.project.yaml; do
      source_project=${source_project_file%/.project.yaml}
      while IFS= read -r source; do
        [[ -n "$source" ]] || continue
        source_path="$source_project/$source"
        if [[ ! -e "$source_path" ]]; then
          printf 'Missing Tailwind source: %s (run mise run sync)\n' "$source_path" >&2
          exit 1
        fi
        if [[ -z ${included_files["$source_project_file"]+x} ]]; then
          files+=("$source_project_file")
          included_files["$source_project_file"]=1
        fi
        while IFS= read -r -d '' file; do
          [[ -f "$file" && -z ${included_files["$file"]+x} ]] || continue
          files+=("$file")
          included_files["$file"]=1
        done < <(git ls-files --cached --others --exclude-standard -z -- "$source_path" | sort -z)
      done < <(yq eval-all -r 'select(documentIndex == 1) | .tailwindSources // [] | .[]' "$source_project_file")
    done
  fi

  if [[ -n "$check" ]]; then
    for file in "$project/Dockerfile" "$project/.dockerignore"; do
      [[ -f "$file" ]] && files+=("$file")
    done
    identity=".generated/bazel-quality/$project.identity"
    quality_targets+=(":${project}_check")
    emit_check_rule "$project" "$identity" "${files[@]}"
  fi
done

{
  printf '\ngenrule(\n'
  printf '    name = "shellcheck",\n'
  printf '    srcs = [\n'
  while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    printf '        %s,\n' "$(quote "$file")"
  done < <(git ls-files --cached --others --exclude-standard -z -- '*.sh' '*.bash' '*.bats' | sort -zu)
  printf '    ],\n'
  printf '    tools = ["mise.toml", ".bazelversion", ".generated/bazel-quality/host.identity"],\n'
  printf '    outs = ["shellcheck.ok"],\n'
  printf '    cmd = "mise exec -- shellcheck %s && touch %s",\n' "\$(SRCS)" "\$@"
  printf '    tags = ["no-sandbox", "no-remote"],\n'
  printf ')\n'
} >> "$output"

manifest=.scripts/tests/groups.yaml
group_specs=$(yq -o=json '.' "$manifest")
if ! jq -e '
  type == "object" and length > 0 and all(to_entries[];
    (.key | test("^[a-z][a-z0-9_]*$")) and
    (.value.tests | type == "array" and length > 0 and all(.[]; type == "string")) and
    (.value.inputs | type == "array" and all(.[]; type == "string" and length > 0)))
' <<< "$group_specs" > /dev/null; then
  printf 'Invalid script test group manifest: %s\n' "$manifest" >&2
  exit 1
fi

declare -A test_groups=()
for group in $(jq -r 'keys[]' <<< "$group_specs"); do
  while IFS= read -r test_file; do
    if [[ "$test_file" != .scripts/tests/*.bats || ! -f "$test_file" ]]; then
      printf 'Missing or invalid script test: %s\n' "$test_file" >&2
      exit 1
    fi
    if [[ -n ${test_groups["$test_file"]+x} ]]; then
      printf 'Script test assigned more than once: %s\n' "$test_file" >&2
      exit 1
    fi
    test_groups["$test_file"]=$group
  done < <(jq -r --arg group "$group" '.[$group].tests[]' <<< "$group_specs")
done

while IFS= read -r -d '' test_file; do
  [[ -f "$test_file" ]] || continue
  if [[ -z ${test_groups["$test_file"]+x} ]]; then
    printf 'Script test is not assigned to a group: %s\n' "$test_file" >&2
    exit 1
  fi
done < <(git ls-files --cached --others --exclude-standard -z -- '.scripts/tests/*.bats' | sort -zu)

for group in $(jq -r 'keys[]' <<< "$group_specs"); do
  declare -A group_files=()
  group_files["$manifest"]=1
  group_files[".scripts/tests/test_helper.bash"]=1
  group_files[".scripts/test-scripts.sh"]=1
  while IFS= read -r test_file; do
    group_files["$test_file"]=1
  done < <(jq -r --arg group "$group" '.[$group].tests[]' <<< "$group_specs")
  while IFS= read -r pattern; do
    matched=false
    while IFS= read -r -d '' file; do
      [[ -f "$file" ]] || continue
      group_files["$file"]=1
      matched=true
    done < <(git ls-files --cached --others --exclude-standard -z -- "$pattern" | sort -zu)
    if [[ "$matched" == false ]]; then
      printf 'Script test group %s input pattern matches no files: %s\n' "$group" "$pattern" >&2
      exit 1
    fi
  done < <(jq -r --arg group "$group" '.[$group].inputs[]' <<< "$group_specs")
  {
    printf '\ngenrule(\n'
    printf '    name = "test_scripts_%s",\n' "$group"
    printf '    srcs = [\n'
    while IFS= read -r file; do
      printf '        %s,\n' "$(quote "$file")"
    done < <(printf '%s\n' "${!group_files[@]}" | sort)
    printf '    ],\n'
    printf '    tools = ["mise.toml", ".bazelversion", ".generated/bazel-quality/host.identity"],\n'
    printf '    outs = ["test-scripts-%s.ok"],\n' "$group"
    printf '    cmd = "mise run --raw test-scripts %s && touch %s",\n' "$group" "\$@"
    printf '    tags = ["no-sandbox", "no-remote"],\n'
    printf ')\n'
  } >> "$output"
done

{
  printf '\nfilegroup(\n'
  printf '    name = "test_scripts",\n'
  printf '    srcs = [\n'
  while IFS= read -r group; do
    printf '        ":test_scripts_%s",\n' "$group"
  done < <(jq -r 'keys[]' <<< "$group_specs")
  printf '    ],\n'
  printf ')\n'
} >> "$output"

{
  printf '\nfilegroup(\n'
  printf '    name = "quality",\n'
  printf '    srcs = [\n'
  for target in "${quality_targets[@]}"; do
    printf '        "%s",\n' "$target"
  done
  printf '        ":shellcheck",\n'
  printf '        ":test_scripts",\n'
  printf '    ],\n'
  printf ')\n'
} >> "$output"

if ! cmp -s "$output" BUILD.bazel; then
  mv "$output" BUILD.bazel
fi
