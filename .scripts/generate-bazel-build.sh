for file in "${integration_shared_inputs[@]}"; do
  if [[ ! -f "$file" ]]; then
    printf 'Missing integration-cache input: %s\n' "$file" >&2
    exit 1
  fi
done
emit_integration_rule() {
  local project=$1 cacheable=$2
  shift 2
  local command
  command="INTEGRATION_BAZEL_ACTION=true bash .scripts/run-integration-suite.sh $(printf '%q' "$project") && touch \$@"
  {
    printf '\ngenrule(\n'
    printf '    name = "integration_suite_%s",\n' "$project"
    printf '    srcs = [\n'
    for file in "$@"; do
      printf '        %s,\n' "$(quote "$file")"
    done
    printf '    ],\n'
    printf '    outs = ["integration-suite-%s.ok"],\n' "$project"
    printf '    cmd = %s,\n' "$(quote "$command")"
    if [[ "$cacheable" == true ]]; then
      printf '    tags = ["manual", "no-sandbox", "no-remote"],\n'
    else
      printf '    tags = ["manual", "no-sandbox", "no-remote", "no-cache"],\n'
    fi
    printf ')\n'
  } >> "$output"
}

for project_file in */.project.yaml; do
  project=${project_file%/.project.yaml}
  category=$(yq eval-all -r 'select(documentIndex == 1) | .category // ""' "$project_file")
  integration=$(yq eval-all -r 'select(documentIndex == 1) | .integration // ""' "$project_file")
  [[ "$category" == test && -n "${integration//[[:space:]]/}" ]] || continue

  dependency_projects=$(jq -r --arg project "$project" '.resolved[$project].projects[]?' "$integration_graph")
  reaches_nats=$(jq -r --arg project "$project" \
    '.resolved[$project].synthetic | index("nats") != null' "$integration_graph")
  integration_rule_files=(
    ".generated/integration-identities/$project.json"
    "$project/.project.yaml"
  )
  while IFS= read -r dependency; do
    [[ -n "$dependency" ]] || continue
    integration_rule_files+=("$dependency/.project.yaml")
  done <<< "$dependency_projects"
  integration_rule_files+=("${integration_shared_inputs[@]}")
  if grep -Fxq graphql <<< "$dependency_projects"; then
    for file in .scripts/create-auth-accounts.sh .scripts/create-auth-test-fixture.sh; do
      if [[ ! -f "$file" ]]; then
        printf 'Missing integration-cache input: %s\n' "$file" >&2
        exit 1
      fi
      integration_rule_files+=("$file")
    done
  fi
  if [[ "$reaches_nats" == true ]]; then
    integration_rule_files+=(message-bus/nats.conf)
  fi
  mapfile -t integration_rule_files \
    < <(printf '%s\n' "${integration_rule_files[@]}" | LC_ALL=C sort -u)
  if [[ ! -f message-bus/nats.conf && "$reaches_nats" == true ]]; then
    printf 'Missing required NATS configuration for integration suite %s: message-bus/nats.conf\n' \
      "$project" >&2
    exit 1
  fi

  dependency_count=$(jq -r --arg project "$project" \
    '.resolved[$project].projects | length' "$integration_graph")
  cacheable=false
  if ((dependency_count > 0)) || [[ "$reaches_nats" == true ]]; then
    cacheable=true
  fi
  emit_integration_rule "$project" "$cacheable" "${integration_rule_files[@]}"
done

