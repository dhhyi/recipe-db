#!/bin/sh
set -eu

project_root=$(cd "$(dirname "$0")/.." && pwd)
cd "$project_root"
. .scripts/lib/ignore-rules.sh

case "$*" in
  "" | --check-sources) ;;
  *)
    echo "usage: $0 [--check-sources]" >&2
    exit 2
    ;;
esac

sources_css="design/src/tailwind-sources.css"
dockerfile="design/Dockerfile"
start_marker="# BEGIN generated Tailwind Docker inputs"
end_marker="# END generated Tailwind Docker inputs"

temporary_directory=$(mktemp -d)
trap 'rm -rf "$temporary_directory"' EXIT

entries="$temporary_directory/entries"
ignores="$temporary_directory/ignores"
: > "$entries"
: > "$ignores"

# $project is a yq variable.
# shellcheck disable=SC2016
mise exec -- yq -N -r \
  'select(documentIndex == 1) | (filename | sub("/.project.yaml$", "")) as $project |
    ((.tailwind.sources // [] | .[] | [$project, "source", .] | @tsv),
     (.tailwind.ignore // [] | .[] | [$project, "ignore", .] | @tsv))' \
  */.project.yaml > "$temporary_directory/metadata"
while IFS="$(printf '\t')" read -r project kind source; do
  [ -n "$project$kind$source" ] || continue
  if [ -z "$source" ]; then
    echo "Tailwind $kind in project $project must not be empty" >&2
    exit 1
  fi

  case "$source" in
    /* | ../* | */../* | */.. | ..)
      echo "Tailwind source $source must be inside project $project" >&2
      exit 1
      ;;
  esac

  if [ "$kind" = ignore ]; then
    case "$source" in
      *[!a-zA-Z0-9_./*?-]*)
        echo "Tailwind ignore $source must be a project-relative path or glob using *, ** or ?" >&2
        exit 1
        ;;
    esac
    source=${source%/}
  fi

  workspace_path="$project/$source"
  if [ "$kind" = source ] && [ ! -f "$workspace_path" ] && [ ! -d "$workspace_path" ]; then
    echo "Tailwind source $workspace_path must be an existing file or directory" >&2
    exit 1
  fi

  # @source paths are resolved relative to the stylesheet in design/src
  case "$workspace_path" in
    design/src/*) tailwind_path=${workspace_path#design/src/} ;;
    design/*) tailwind_path="../${workspace_path#design/}" ;;
    *) tailwind_path="../../$workspace_path" ;;
  esac

  if [ "$kind" = ignore ]; then
    printf '%s\t%s\n' "$tailwind_path" "$workspace_path" >> "$ignores"
  else
    printf '%s\t%s\t%s\n' "$tailwind_path" "$project" "$workspace_path" >> "$entries"
  fi
done < "$temporary_directory/metadata"

if [ "${1:-}" = --check-sources ]; then
  exit 0
fi

LC_ALL=C sort -o "$entries" "$entries"
LC_ALL=C sort -o "$ignores" "$ignores"

echo "Writing $sources_css ..."
{
  echo "/* This file is generated by sync-tailwind.sh. Do not edit it manually. */"
  echo
  cut -f1 "$entries" | sed 's|.*|@source "&";|'
  cut -f1 "$ignores" | sed 's|.*|@source not "&";|'
} > "$sources_css"

block="$temporary_directory/block"
{
  echo "$start_marker"
  echo "# This section is generated by sync-tailwind.sh. Do not edit it manually."
  echo
  awk -F'\t' '$2 != "design" { printf "COPY [\"%s\",\"/%s\"]\n", $3, $3 }' "$entries"
  echo "$end_marker"
} > "$block"

echo "Writing generated Tailwind Docker inputs in $dockerfile ..."
awk -v block="$block" -v start="$start_marker" -v end="$end_marker" -v file="$dockerfile" '
  $0 == start {
    starts++
    if (starts == 1) {
      while ((getline line < block) > 0) print line
      skipping = 1
      next
    }
  }
  $0 == end {
    ends++
    if (skipping) {
      skipping = 0
      next
    }
  }
  !skipping
  END {
    if (starts != 1 || ends != 1) {
      printf "expected exactly one marker pair in %s\n", file > "/dev/stderr"
      exit 1
    }
  }
' "$dockerfile" > "$temporary_directory/dockerfile"
mv "$temporary_directory/dockerfile" "$dockerfile"

echo "Writing design/Dockerfile.dockerignore ..."
design_ignores=$(project_docker_ignores design)
project_root_docker_ignores > "$temporary_directory/project-root-ignores"
project_default_docker_ignores > "$temporary_directory/project-default-ignores"
{
  echo "# This file is generated by sync-tailwind.sh. Do not edit it manually."
  echo
  echo '**'
  echo '!/design'
  echo '!/design/**'
  awk -F'\t' '$2 != "design" {
    sources[++source_count] = $3
    count = split($3, parts, "/")
    path = ""
    for (i = 1; i < count; i++) {
      path = path "/" parts[i]
      if (!seen[path]++) {
        print "!" path
        print path "/*"
      }
    }
  }
  END {
    for (i = 1; i <= source_count; i++) {
      print "!/" sources[i]
      print "!/" sources[i] "/**"
    }
  }' "$entries"
  echo
  root_docker_ignores
  echo
  prefix_ignore_rules design docker < "$temporary_directory/project-root-ignores"
  echo
  printf '%s\n' "$design_ignores" | prefix_ignore_rules design docker
  echo
  prefix_ignore_rules design docker < "$temporary_directory/project-default-ignores"
  echo
  cut -f2 "$ignores" | sed 's|^|/|'
} > design/Dockerfile.dockerignore
