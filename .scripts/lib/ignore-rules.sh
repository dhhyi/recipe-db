#!/bin/sh

prefix_ignore_rules() {
  awk -v project="$1" -v docker="${2:-}" '
    $0 == "" || substr($0, 1, 1) == "#" { print; next }
    {
      line = $0
      negation = ""
      if (substr(line, 1, 1) == "!") {
        negation = "!"
        line = substr(line, 2)
      }
      if (substr(line, 1, 1) == "/") separator = ""
      else if (docker == "docker" || index(line, "/") > 0) separator = "/"
      else separator = "/**/"
      print negation "/" project separator line
    }
  '
}

project_root_docker_ignores() {
  # Generated schemas are needed in project-local build contexts.
  awk '$0 != "recipe-db.graphqls"' .gitignore
}

project_default_docker_ignores() {
  printf '%s\n' .project.yaml .gitignore README.md Dockerfile
}

project_docker_ignores() {
  mise exec -- yq -r \
    'select(documentIndex == 1) | .docker.ignore // [] | .[]' \
    "$1/.project.yaml"
}

root_docker_ignores() {
  echo "# This file is generated by sync-ignore-files.sh. Do not edit it manually."
  echo
  cat .gitignore
  cat << 'EOF'

# nested dependency and build output
**/.git
**/.devcontainer
**/.pnpm-store
**/.vscode
**/dist
**/elm-stuff
**/node_modules
**/storybook-static
**/target
EOF
}
